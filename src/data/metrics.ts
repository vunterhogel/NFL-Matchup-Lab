export function evaluateMetric(
  definition: MetricDefinition,
  stats: Record<string, number>,
): number | null {
  const denominator = stats[definition.denominator] ?? 0;
  if (!Number.isFinite(denominator) || denominator <= 0) return null;
  const numerator = stats[definition.numerator] ?? 0;
  return Number.isFinite(numerator)
    ? (numerator / denominator) * definition.multiplier
    : null;
}

/** Midrank percentile; ties share a score. A single valid observation is 50th percentile. */
export function computePercentile(
  value: number | null,
  values: (number | null)[],
  higherIsBetter = true,
): number | null {
  if (value === null || !Number.isFinite(value)) return null;
  const valid = values.filter(
    (v): v is number => v !== null && Number.isFinite(v),
  );
  if (!valid.length) return null;
  if (valid.length === 1) return 50;
  const better = valid.filter((v) =>
    higherIsBetter ? v < value - 1e-10 : v > value + 1e-10,
  ).length;
  const equal = valid.filter((v) => Math.abs(v - value) < 1e-10).length;
  return Math.max(
    0,
    Math.min(100, (100 * (better + (equal - 1) / 2)) / (valid.length - 1)),
  );
}
